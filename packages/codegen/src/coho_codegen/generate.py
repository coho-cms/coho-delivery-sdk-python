"""
The Python for a type model: a module per content type holding its Pydantic model, such as
`blog_post.py`, one per component type and per trait, and `__init__.py`, which imports them
all and adds each base type's family, the content types' union, the shape the runtime
hydrates with, the model's source, and the clients, `Coho` and `AsyncCoho`.

A pure function of the model, so the same model always gives the same bytes and a drift
check can compare them. Nothing about the generator's own version is written, for the same
reason.
"""

from __future__ import annotations

import json
import keyword
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass, field
from typing import Literal

from .model import CodegenError, ContentType, Field, Trait, TypeModel

GENERATED_MARK = "# Generated by coho-codegen from the Coho type model."
"""How every generated file starts, so a later run knows which files are its own to remove."""

HEADER = f"{GENERATED_MARK} Do not edit: run `coho-codegen generate`."

INDENT = "    "

RESERVED_CLASS_NAMES = frozenset(
    ["AnyEntry", "AsyncCoho", "Coho", "Linked", "RepeaterItem", "Unresolved"]
)
"""
Names the generated package defines or re-exports. A content type whose class would be one of
these is given `Entry` after it instead, so no project's types can shadow them.
"""

RESERVED_MEMBERS = frozenset(["by_slug", "by_id", "by_ids", "content", "close", "aclose"])
"""What `Coho` has besides its readers. A type that would be read as one of these is read as `<name>_type`."""

RESERVED_ATTRIBUTES = frozenset(
    [
        # The system values every entry and item has.
        "id",
        "type",
        "slug",
        "locale",
        # Names the generated modules import, which a field must not hide.
        "datetime",
        "runtime",
        # Pydantic's own, which a field must not shadow.
        "copy",
        "dict",
        "json",
        "schema",
        "schema_json",
        "construct",
        "validate",
        "parse_obj",
        "parse_raw",
        "parse_file",
        "from_orm",
        "update_forward_refs",
    ]
)
"""
Attribute names a field cannot have. A field id that would map to one, or to a keyword or a
`model_` name, is given `_` after it, and keeps its id on the wire.
"""

RASTER_IMAGES = frozenset(
    ["image/png", "image/jpeg", "image/gif", "image/webp", "image/avif", "image/heic"]
)


@dataclass(frozen=True)
class GeneratedFile:
    path: str
    """Relative to the output directory."""

    contents: str


@dataclass(frozen=True)
class Generated:
    files: list[GeneratedFile]
    warnings: list[str]
    """Things to tell whoever ran the generator. Never fatal."""


def snake(name: str) -> str:
    """`publishedAt` becomes `published_at`, and `seoURL` `seo_url`."""
    name = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", name)
    name = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", name)
    return name.lower()


def _safe(name: str) -> str:
    """A name Python lets you use: a keyword gets `_` after it."""
    return f"{name}_" if keyword.iskeyword(name) or keyword.issoftkeyword(name) else name


def generate(model: TypeModel) -> Generated:
    warnings: list[str] = []
    for warning in model.get("warnings", []):
        warnings.append(f"{warning['type']}.{warning['field']}: {warning['message']}")
    source = model["source"]
    if not source["immutable"]:
        warnings.append(
            f"Generated from '{source['ref']}', a branch: its types can change. "
            "Release builds should name a tag."
        )

    types = [model["types"][slug] for slug in sorted(model["types"])]
    # Since type model 1.2. Content and component types share one slug namespace, so they
    # share one set of names too.
    components_map = model.get("components", {})
    components = [components_map[slug] for slug in sorted(components_map)]
    # Since type model 1.4: a trait is a Protocol every type with it satisfies. Traits share
    # the slug namespace too, and with it the names.
    traits_map = model.get("traits", {})
    traits = [traits_map[slug] for slug in sorted(traits_map)]

    names = _Names([*types, *components, *traits], warnings)
    # Since type model 1.3: delivery lists a type with its descendants, so a read or a link
    # of a base type is any type in its family.
    family = _Families([*types, *components], names, warnings)
    context = _Context(names, family, warnings)

    files = [
        _index_file(model, types, components, traits, context),
        *(_type_file(each, "content", context) for each in types),
        *(_type_file(each, "component", context) for each in components),
        *(_trait_file(each, context) for each in traits),
    ]
    return Generated(files=files, warnings=warnings)


class _Names:
    """Each type's class and module, from its slug: `blogPost` is `BlogPost`, in `blog_post.py`."""

    def __init__(self, types: Sequence[ContentType | Trait], warnings: list[str]):
        self.classes: dict[str, str] = {}
        self.modules: dict[str, str] = {}
        taken: set[str] = set()
        modules: dict[str, str] = {}
        for each in types:
            slug = each["slug"]
            name = slug[:1].upper() + slug[1:]
            if name in RESERVED_CLASS_NAMES:
                warnings.append(
                    f"Type '{slug}' is named {name}Entry, because {name} is taken by the generated code."
                )
                name = f"{name}Entry"
            if name in taken:
                raise CodegenError(f"Two types would both be named {name}; rename one of them")
            taken.add(name)
            module = _safe(snake(slug))
            if module in modules:
                raise CodegenError(
                    f"'{modules[module]}' and '{slug}' would both be {module}.py; rename one of them"
                )
            modules[module] = slug
            self.classes[slug] = name
            self.modules[slug] = module

    def has(self, slug: str) -> bool:
        return slug in self.classes

    def of(self, slug: str) -> str:
        return self.classes.get(slug, "runtime.HydratedEntry")


class _Families:
    """
    Type inheritance (type model 1.3). Delivery lists a type with its descendants, and a link
    or an item of a base type may be any of them, so a base type has a **family**: the
    concrete types an entry or item of it can be, itself unless abstract, and every concrete
    descendant. A type with descendants is read and linked as its family's alias, `AnyPage`;
    a type with none, as itself.
    """

    def __init__(self, types: Sequence[ContentType], names: _Names, warnings: list[str]):
        self._types = {each["slug"]: each for each in types}
        self._names = names
        self._below: dict[str, list[str]] = {}
        for each in types:
            # Each ancestor on the ref, cycle-guarded: the server refuses a cycle, so this
            # only stops a broken file.
            seen = {each["slug"]}
            parent = each.get("extends")
            while parent is not None and parent in self._types and parent not in seen:
                seen.add(parent)
                self._below.setdefault(parent, []).append(each["slug"])
                parent = self._types[parent].get("extends")

        taken = set(names.classes.values())
        self._aliases: dict[str, str] = {}
        for slug in sorted(self._below):
            name = names.of(slug)
            alias = f"Any{name}"
            if alias in taken or alias in RESERVED_CLASS_NAMES:
                warnings.append(
                    f"The types that extend '{slug}' are named {name}Family, because {alias} is taken."
                )
                alias = f"{name}Family"
            if alias in taken:
                raise CodegenError(
                    f"The family of '{slug}' would be named {alias}, which a type already is; rename one of them"
                )
            taken.add(alias)
            self._aliases[slug] = alias

    def members(self, slug: str) -> list[str]:
        """The concrete types in `slug`'s family, sorted by slug."""
        return sorted(
            each
            for each in [slug, *self._below.get(slug, [])]
            if each in self._types and not self._types[each].get("abstract", False)
        )

    def has(self, slug: str) -> bool:
        """Whether `slug` has descendants, and so a family alias."""
        return slug in self._aliases and len(self.members(slug)) > 0

    def alias(self, slug: str) -> str:
        return self._aliases.get(slug, self._names.of(slug))

    def target(self, slug: str) -> str:
        """How a read or a link of `slug` is typed: its family's alias, or itself."""
        return self.alias(slug) if self.has(slug) else self._names.of(slug)

    def concrete(self, slugs: Iterable[str]) -> list[str]:
        """The concrete types a link or an item naming `slugs` may be, in order, once each."""
        out: list[str] = []
        for slug in slugs:
            for each in self.members(slug) if self.has(slug) else [slug]:
                if each not in out:
                    out.append(each)
        return out

    def is_alias(self, name: str) -> bool:
        return name in self._aliases.values()


@dataclass
class _Context:
    names: _Names
    family: _Families
    warnings: list[str]


@dataclass
class _Imports:
    """What one module uses, so it imports exactly that."""

    std: dict[str, set[str]] = field(default_factory=dict)
    field_: bool = False
    checking: dict[str, set[str]] = field(default_factory=dict)
    """Names only annotations use, by the module they are in: imported for type checkers alone."""

    def use(self, module: str, name: str) -> None:
        self.std.setdefault(module, set()).add(name)

    def check(self, module: str, name: str) -> None:
        self.checking.setdefault(module, set()).add(name)


def _attributes(fields: Sequence[Field], owner: str) -> dict[str, str]:
    """Each field's Python name, by field id."""
    out: dict[str, str] = {}
    seen: dict[str, str] = {}
    for each in fields:
        name = snake(each["id"])
        if (
            name in RESERVED_ATTRIBUTES
            or name.startswith("model_")
            or keyword.iskeyword(name)
            or keyword.issoftkeyword(name)
        ):
            name = f"{name}_"
        if name in seen:
            raise CodegenError(
                f"{owner}: '{seen[name]}' and '{each['id']}' would both be {name} in Python; rename one of them"
            )
        seen[name] = each["id"]
        out[each["id"]] = name
    return out


def _python_type(owner: str, each: Field, context: _Context, imports: _Imports) -> tuple[str, bool]:
    """A field's Python type, and whether it is a list."""
    kind = each["kind"]
    family = context.family
    names = context.names
    many = each.get("many", False)

    def linked(slug: str) -> str:
        name = family.target(slug)
        return name

    if kind in ("text", "longText"):
        return "str", False
    if kind == "datetime":
        imports.use("datetime", "datetime")
        return "datetime", False
    if kind == "integer":
        return "int", False
    if kind == "number":
        return "float", False
    if kind == "boolean":
        return "bool", False
    if kind == "json":
        imports.use("typing", "Any")
        return "Any", False
    if kind == "choice":
        return _choices(each, imports), False
    if kind == "multichoice":
        return f"list[{_choices(each, imports)}]", True
    if kind == "reference":
        # An empty `of` means the target's type is not on this ref: an untyped entry.
        targets = [slug for slug in each.get("of", []) if names.has(slug)]
        kinds = list(dict.fromkeys(linked(slug) for slug in targets)) or ["runtime.HydratedEntry"]
        link = f"runtime.Linked[{' | '.join(kinds)}]"
        return (f"list[{link}]", True) if many else (link, False)
    if kind == "asset":
        # Embedded by delivery, never a link to follow. One that is gone on the ref is None,
        # required or not, so a single asset is always optional; in a list it is left out.
        asset = "runtime.ImageAsset" if _image_only(each) else "runtime.Asset"
        return (f"list[{asset}]", True) if many else (f"{asset} | None", False)
    if kind == "repeater":
        # A union of the components on the ref. The runtime leaves out an item of any other
        # component (the shape's `items`), so the union is never wrong about what it holds.
        components = [slug for slug in each.get("of", []) if names.has(slug)]
        if not components:
            return "list[runtime.RepeaterItem]", True
        kinds = list(dict.fromkeys(linked(slug) for slug in components))
        return f"list[{' | '.join(kinds)}]", True
    context.warnings.append(
        f"{owner}.{each['id']} is a '{kind}', which this generator does not know; it is typed Any. "
        "Upgrade coho-codegen."
    )
    imports.use("typing", "Any")
    return "Any", False


def _choices(each: Field, imports: _Imports) -> str:
    """
    A choice's values, and any other text: content may hold a value added after this code
    was generated, and that must not fail to validate.
    """
    values = each.get("values", [])
    if not values:
        return "str"
    imports.use("typing", "Literal")
    return f"Literal[{', '.join(_literal(value) for value in values)}] | str"


def _image_only(each: Field) -> bool:
    """Whether every file the field accepts is a raster image, which always has dimensions."""
    accept = each.get("accept", [])
    return len(accept) > 0 and all(media in RASTER_IMAGES for media in accept)


def _literal(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def _note(each: Field, is_list: bool) -> str:
    notes: list[str] = []
    kind = each["kind"]
    if kind == "asset" and each.get("accept"):
        notes.append(f"Accepts {', '.join(each.get('accept', []))}.")
    if kind == "asset" and not each.get("many", False):
        notes.append("None where the asset it linked is gone.")
    if kind == "longText" and each.get("textFormat") == "markdown":
        notes.append("Markdown.")
    if kind == "longText" and each.get("textFormat") == "html":
        notes.append("HTML.")
    if each.get("localized", False):
        notes.append(f"{'Empty' if is_list else 'None'} where the locale has no translation.")
    return " ".join(notes)


def _doc(name: str, note: str = "") -> str:
    """A one-line docstring. Names are content, so quotes and backslashes in one are escaped."""
    text = ". ".join(part for part in (" ".join(name.split()), note) if part)
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if text.endswith('"'):
        text = f'{text[:-1]}\\"'
    return f'"""{text}"""'


def _listed(names: Sequence[str]) -> str:
    """`A`, `A and B`, or `A, B, and C`."""
    if len(names) <= 2:
        return " and ".join(names)
    return f"{', '.join(names[:-1])}, and {names[-1]}"


def _default(each: Field, is_list: bool) -> str | None:
    """The default a field's declaration takes, or None when it has none: delivery always sends it."""
    if each["presence"] == "always":
        return None
    return "[]" if is_list else "None"


def _declaration(attribute: str, wire: str, python: str, default: str | None) -> str:
    """`published_at: datetime = Field(alias="publishedAt")`, or as little of that as it needs."""
    if attribute == wire:
        return f"{attribute}: {python}" if default is None else f"{attribute}: {python} = {default}"
    alias = f"alias={_literal(wire)}"
    if default is None:
        return f"{attribute}: {python} = Field({alias})"
    if default == "[]":
        return f"{attribute}: {python} = Field(default_factory=list, {alias})"
    return f"{attribute}: {python} = Field(default={default}, {alias})"


def _always(each: Field) -> str:
    """
    What an entry without the field gets, as old entries can after a field becomes required:
    the empty value of its kind, so the entry still validates. The runtime reports it.
    """
    kind = each["kind"]
    if each.get("many", False) or kind in ("multichoice", "repeater"):
        return "[]"
    return {
        "text": '""',
        "longText": '""',
        "choice": '""',
        "datetime": '"0001-01-01T00:00:00Z"',
        "integer": "0",
        "number": "0",
        "boolean": "False",
        "reference": '{"_id": "", "_unresolved": "absent"}',
    }.get(kind, "None")


def _type_file(
    each: ContentType, kind: Literal["content", "component"], context: _Context
) -> GeneratedFile:
    """
    One content or component type's model. A component is a repeater item, so it derives from
    `ItemBase`, with an `id` and `type`, where a content type derives from `EntryBase`. A type
    that extends another derives from its model, and declares only what it adds or tightens.
    """
    names, family = context.names, context.family
    slug = each["slug"]
    name = names.of(slug)
    imports = _Imports()

    parent_slug = each.get("extends")
    parent = names.of(parent_slug) if parent_slug is not None and names.has(parent_slug) else None
    base = parent or ("runtime.ItemBase" if kind == "component" else "runtime.EntryBase")
    own = [f for f in each["fields"] if parent is None or not f.get("inherited", False)]
    attributes = _attributes(each["fields"], slug)

    # An abstract type's entries are its descendants', so its `type` is any of theirs; a base
    # type's is any in its family, so each subtype's narrows it.
    members = family.members(slug) if family.has(slug) else []
    discriminants = members if members else [slug]
    imports.use("typing", "Literal")
    imports.field_ = True

    traits = [names.of(t) for t in each.get("traits", []) if names.has(t)]
    summary = " ".join(
        part
        for part in (
            "A repeater item, stored in the entry that holds it." if kind == "component" else "",
            f"Extends {parent}, and has every field it has." if parent is not None else "",
            f"Abstract: {'an item' if kind == 'component' else 'an entry'} is one of the types that extend it."
            if each.get("abstract", False)
            else "",
            f"Has the trait{'' if len(traits) == 1 else 's'} {_listed(traits)}." if traits else "",
        )
        if part
    )

    body: list[str] = [
        f"{INDENT}{_doc(each['name'], summary)}",
        "",
        f'{INDENT}type: Literal[{", ".join(_literal(d) for d in discriminants)}] = Field(alias="_type")',
    ]
    for each_field in own:
        python, is_list = _python_type(slug, each_field, context, imports)
        default = _default(each_field, is_list)
        if default is not None and default != "[]" and not python.endswith("| None"):
            python = f"{python} | None"
        declaration = _declaration(attributes[each_field["id"]], each_field["id"], python, default)
        if "Field(" in declaration:
            imports.field_ = True
        body += [
            "",
            f"{INDENT}{declaration}",
            f"{INDENT}{_doc(each_field['name'], _note(each_field, is_list))}",
        ]

    sortable = [f["id"] for f in each["fields"] if f.get("sortable", False)]
    after: list[str] = []
    if sortable and kind == "content":
        orders = [option for wire in sortable for option in (wire, f"-{wire}")]
        after = [
            "",
            "",
            f"{name}Order = Literal[{', '.join(_literal(o) for o in orders)}]",
            '"""What a list of these can be ordered by: a sortable field, or one with `-` before it for descending."""',
        ]

    _annotations_from(own, slug, name, context, imports)
    if parent is not None:
        imports.checking.pop(names.modules[parent_slug or ""], None)
    uses_runtime = parent is None or any("runtime." in line for line in body)
    lines = [
        HEADER,
        "",
        "from __future__ import annotations",
        "",
        *_import_lines(
            imports,
            runtime=uses_runtime,
            parent=(names.modules[parent_slug], parent) if parent and parent_slug else None,
        ),
        "",
        "",
        f"class {name}({base}):",
        *body,
        *after,
    ]
    return GeneratedFile(path=f"{names.modules[slug]}.py", contents="\n".join(lines) + "\n")


def _annotations_from(
    fields: Sequence[Field], slug: str, name: str, context: _Context, imports: _Imports
) -> None:
    """The classes and families a type's annotations name, imported for type checkers."""
    names, family = context.names, context.family
    for each in fields:
        if each["kind"] not in ("reference", "repeater"):
            continue
        for target in each.get("of", []):
            if not names.has(target):
                continue
            used = family.target(target)
            if used == name:
                continue
            if family.is_alias(used):
                imports.check("", used)
            else:
                imports.check(names.modules[target], used)


def _import_lines(
    imports: _Imports, *, runtime: bool, parent: tuple[str, str] | None = None
) -> list[str]:
    std = dict(imports.std)
    if imports.checking:
        std.setdefault("typing", set()).add("TYPE_CHECKING")
    lines: list[str] = []
    for module in sorted(std):
        lines.append(f"from {module} import {', '.join(sorted(std[module], key=_import_order))}")
    third: list[str] = []
    if imports.field_:
        third.append("from pydantic import Field")
    if runtime:
        third.append("")
        third.append("import coho_delivery_sdk as runtime")
    if lines and third:
        lines.append("")
    lines += [line for i, line in enumerate(third) if not (line == "" and i == 0)]
    if parent is not None:
        lines += ["", f"from .{parent[0]} import {parent[1]}"]
    if imports.checking:
        lines += ["", "if TYPE_CHECKING:"]
        for module in sorted(imports.checking, key=lambda m: (m != "", m)):
            source = "." if module == "" else f".{module}"
            what = ", ".join(sorted(imports.checking[module]))
            lines.append(f"{INDENT}from {source} import {what}")
    return lines


def _import_order(name: str) -> tuple[int, str]:
    # isort's: constants, then classes, then functions.
    return (0 if name.isupper() else 1 if name[:1].isupper() else 2, name)


def _trait_file(trait: Trait, context: _Context) -> GeneratedFile:
    """
    A trait (type model 1.4): a Protocol of the fields it declares, which every type that has
    it satisfies. Each type still declares those fields itself, as it has them, which may be
    tighter than the trait's. So a function that takes a `Seo` takes an entry of any type
    with the trait.
    """
    names = context.names
    name = names.of(trait["slug"])
    imports = _Imports()
    imports.use("typing", "Protocol")
    imports.use("typing", "runtime_checkable")
    attributes = _attributes(trait["fields"], trait["slug"])

    body = [
        f"{INDENT}{_doc(trait['name'], 'A trait: fields every type with it has. Take it to accept an entry of any of them.')}",
    ]
    uses_runtime = False
    for each in trait["fields"]:
        python, is_list = _python_type(trait["slug"], each, context, imports)
        if is_list:
            # A sequence, not a list, so a type that narrows the items still satisfies it.
            imports.use("collections.abc", "Sequence")
            python = f"Sequence{python[len('list') :]}"
        elif each["presence"] != "always" and not python.endswith("| None"):
            python = f"{python} | None"
        uses_runtime = uses_runtime or "runtime." in python
        body += [
            "",
            f"{INDENT}@property",
            f"{INDENT}def {attributes[each['id']]}(self) -> {python}:",
            f"{INDENT}{INDENT}{_doc(each['name'], _note(each, is_list))}",
        ]
    _annotations_from(trait["fields"], trait["slug"], name, context, imports)

    lines = [
        HEADER,
        "",
        "from __future__ import annotations",
        "",
        *_import_lines(imports, runtime=uses_runtime),
        "",
        "",
        "@runtime_checkable",
        f"class {name}(Protocol):",
        *body,
    ]
    return GeneratedFile(
        path=f"{names.modules[trait['slug']]}.py", contents="\n".join(lines) + "\n"
    )


def _index_file(
    model: TypeModel,
    types: Sequence[ContentType],
    components: Sequence[ContentType],
    traits: Sequence[Trait],
    context: _Context,
) -> GeneratedFile:
    """`__init__.py`: every type, and what reads them."""
    names, family = context.names, context.family
    source = model["source"]
    kind = "a tag" if source["immutable"] else "a branch, whose types can change"

    # Each module's names, and the package's own.
    exported: list[str] = []
    imports: dict[str, list[str]] = {}
    for each in [*types, *components]:
        module = names.modules[each["slug"]]
        imports.setdefault(module, []).append(names.of(each["slug"]))
        exported.append(names.of(each["slug"]))
        if any(f.get("sortable", False) for f in each["fields"]) and each in types:
            imports[module].append(f"{names.of(each['slug'])}Order")
            exported.append(f"{names.of(each['slug'])}Order")
    for trait in traits:
        imports.setdefault(names.modules[trait["slug"]], []).append(names.of(trait["slug"]))
        exported.append(names.of(trait["slug"]))

    # An abstract type has no entries of its own, so it is not one of the types an entry is.
    concrete = [each for each in types if not each.get("abstract", False)]
    readers = _readers(types, context)
    typing_names = {"TYPE_CHECKING", "TypeAlias", "cast"}
    if not concrete or any(r.order == "Never" for r in readers):
        typing_names.add("Never")

    out: list[str] = [
        HEADER,
        f"# Project {source['project']}, ref {source['ref']} ({kind}), schema {source['schemaHash']}, "
        f"type model {model['irVersion']}.",
        "",
        "from __future__ import annotations",
        "",
        f"from typing import {', '.join(sorted(typing_names, key=_import_order))}",
        "",
        "import coho_delivery_sdk as runtime",
        "from coho_delivery_sdk import Linked, Unresolved, is_resolved, resolved",
        "",
        *(f"from .{module} import {', '.join(imports[module])}" for module in sorted(imports)),
        *([""] if imports else []),
        "if TYPE_CHECKING:",
        f"{INDENT}import httpx",
    ]

    # Families: a base type's read and links are any type in it.
    for each in [*types, *components]:
        slug = each["slug"]
        if not family.has(slug):
            continue
        members = [names.of(m) for m in family.members(slug)]
        alias = family.alias(slug)
        exported.append(alias)
        out += [
            "",
            f"{alias}: TypeAlias = {' | '.join(members)}",
            _doc(
                f"A {each['name']} of any kind: {', '.join(members)}",
                "Check with isinstance to narrow it.",
            ),
        ]

    out += [
        "",
        f"AnyEntry: TypeAlias = {' | '.join(names.of(each['slug']) for each in concrete) if concrete else 'Never'}",
        '"""Any content type on this ref. Check with isinstance, or match on `type`, to narrow it."""',
        "",
        f"content_types: tuple[str, ...] = {_tuple([each['slug'] for each in concrete])}",
        '"""The types an entry can be: every content type that is not abstract."""',
        "",
        *_shape(types, components, context),
        "",
        "source = runtime.Source(",
        f"{INDENT}project={_literal(source['project'])},",
        f"{INDENT}ref={_literal(source['ref'])},",
        f"{INDENT}immutable={source['immutable']},",
        f"{INDENT}schema_hash={_literal(source['schemaHash'])},",
        f"{INDENT}ir_version={_literal(model['irVersion'])},",
        ")",
        '"""Where these types came from, for reporting which release a build was made from."""',
        "",
        *_client(readers, asynchronous=False),
        "",
        *_client(readers, asynchronous=True),
        "",
        "",
        *_rebuild([names.of(each["slug"]) for each in [*types, *components]]),
        "__all__ = [",
        *(
            f"{INDENT}{_literal(n)},"
            for n in sorted(
                [
                    *exported,
                    "AnyEntry",
                    "AsyncCoho",
                    "Coho",
                    "Linked",
                    "Unresolved",
                    "content_types",
                    "is_resolved",
                    "resolved",
                    "shape",
                    "source",
                ]
            )
        ),
        "]",
    ]
    return GeneratedFile(path="__init__.py", contents="\n".join(out) + "\n")


def _shape(
    types: Sequence[ContentType], components: Sequence[ContentType], context: _Context
) -> list[str]:
    names, family = context.names, context.family
    doc = '"""What the runtime needs to build each type: its model, its links, the fields it always has, and the components each repeater holds."""'
    if not types and not components:
        return ["shape: runtime.Shape = {}", doc]
    lines = ["shape: runtime.Shape = {"]
    for each in [*types, *components]:
        links = [
            f"{_literal(f['id'])}: runtime.Link(many={f.get('many', False)}{_targets(f, context)}),"
            for f in each["fields"]
            if f["kind"] == "reference"
        ]
        always = [
            f"{_literal(f['id'])}: {_always(f)},"
            for f in each["fields"]
            if f["presence"] == "always"
        ]
        items = [
            f"{_literal(f['id'])}: {_tuple(family.concrete(slug for slug in f.get('of', []) if names.has(slug)))},"
            for f in each["fields"]
            if f["kind"] == "repeater" and any(names.has(slug) for slug in f.get("of", []))
        ]
        lines += [
            f"{INDENT}{_literal(each['slug'])}: runtime.TypeShape(",
            f"{INDENT * 2}model={names.of(each['slug'])},",
        ]
        for label, entries in (("links", links), ("always", always), ("items", items)):
            if entries:
                lines += [
                    f"{INDENT * 2}{label}={{",
                    *(f"{INDENT * 3}{entry}" for entry in entries),
                    f"{INDENT * 2}}},",
                ]
        lines.append(f"{INDENT}),")
    lines += ["}", doc]
    return lines


def _tuple(values: Sequence[str]) -> str:
    """A tuple literal of strings, `("a",)` for one."""
    return f"({''.join(f'{_literal(v)}, ' for v in values).rstrip()})"


def _targets(each: Field, context: _Context) -> str:
    targets = [slug for slug in each.get("of", []) if context.names.has(slug)]
    if not targets:
        return ""
    return f", targets={_tuple(context.family.concrete(targets))}"


@dataclass(frozen=True)
class _Reader:
    member: str
    slug: str
    name: str
    target: str
    order: str
    family: list[str] | None


def _readers(types: Sequence[ContentType], context: _Context) -> list[_Reader]:
    names, family = context.names, context.family
    members: set[str] = set()
    out: list[_Reader] = []
    for each in types:
        slug = each["slug"]
        member = _safe(snake(slug))
        if member in RESERVED_MEMBERS:
            context.warnings.append(
                f"Type '{slug}' is read as coho.{member}_type, because coho.{member} is taken by the client."
            )
            member = f"{member}_type"
        if member in members:
            raise CodegenError(f"Two types would both be read as coho.{member}; rename one of them")
        members.add(member)
        sortable = any(f.get("sortable", False) for f in each["fields"])
        out.append(
            _Reader(
                member=member,
                slug=slug,
                name=each["name"],
                target=family.target(slug),
                order=f"{names.of(slug)}Order" if sortable else "Never",
                family=family.members(slug) if family.has(slug) else None,
            )
        )
    return out


def _client(readers: Sequence[_Reader], *, asynchronous: bool) -> list[str]:
    cls = "AsyncCoho" if asynchronous else "Coho"
    reader = "runtime.AsyncTypeReader" if asynchronous else "runtime.TypeReader"
    content = "runtime.AsyncContentClient" if asynchronous else "runtime.ContentClient"
    http = "httpx.AsyncClient" if asynchronous else "httpx.Client"
    a = "async " if asynchronous else ""
    w = "await " if asynchronous else ""
    doc = (
        '"""Typed reads of every content type, awaited, on the ref and in the locale the config names."""'
        if asynchronous
        else '"""Typed reads of every content type, on the ref and in the locale the config names."""'
    )
    lines = ["", f"class {cls}:", f"{INDENT}{doc}", ""]
    for each in readers:
        lines += [
            f"{INDENT}{each.member}: {reader}[{each.target}, {each.order}]",
            f"{INDENT}{_doc(each.name)}",
            "",
        ]
    lines += [
        f"{INDENT}def __init__(",
        f"{INDENT}{INDENT}self,",
        f"{INDENT}{INDENT}config: runtime.ContentConfig,",
        f"{INDENT}{INDENT}*,",
        f"{INDENT}{INDENT}http_client: {http} | None = None,",
        f"{INDENT}{INDENT}cache_size: int = 1000,",
        f"{INDENT}{INDENT}on_issue: runtime.OnIssue | None = None,",
        f"{INDENT}):",
        f'{INDENT}{INDENT}"""A client for these types. The credential comes from the app: this library reads no environment."""',
        f"{INDENT}{INDENT}self.content = {content}(",
        f"{INDENT}{INDENT}{INDENT}config, shape, http_client=http_client, cache_size=cache_size, on_issue=on_issue",
        f"{INDENT}{INDENT})",
        f'{INDENT}{INDENT}"""The untyped reads underneath, for anything the typed ones do not cover."""',
    ]
    for each in readers:
        family = f", {_tuple(each.family)}" if each.family else ""
        lines.append(
            f"{INDENT}{INDENT}self.{each.member} = self.content.type({_literal(each.slug)}{family})"
        )
    lines += [
        "",
        f"{INDENT}{a}def by_slug(self, slug: str, *, depth: int | None = None, locale: str | None = None) -> AnyEntry | None:",
        f'{INDENT}{INDENT}"""The entry with this slug, whatever its type, or None."""',
        f'{INDENT}{INDENT}return cast("AnyEntry | None", {w}self.content.by_slug(slug, depth=depth, locale=locale))',
        "",
        f"{INDENT}{a}def by_id(self, id: str, *, depth: int | None = None, locale: str | None = None) -> AnyEntry | None:",
        f'{INDENT}{INDENT}"""The entry with this id, whatever its type, or None."""',
        f'{INDENT}{INDENT}return cast("AnyEntry | None", {w}self.content.by_id(id, depth=depth, locale=locale))',
        "",
        f"{INDENT}{a}def by_ids(",
        f"{INDENT}{INDENT}self, ids: list[str], *, depth: int | None = None, locale: str | None = None",
        f"{INDENT}) -> list[AnyEntry]:",
        f'{INDENT}{INDENT}"""The entries that exist, sorted by id. Ids not on the ref are left out."""',
        f'{INDENT}{INDENT}return cast("list[AnyEntry]", {w}self.content.by_ids(ids, depth=depth, locale=locale))',
        "",
    ]
    if asynchronous:
        lines += [
            f"{INDENT}async def aclose(self) -> None:",
            f"{INDENT}{INDENT}await self.content.aclose()",
            "",
            f"{INDENT}async def __aenter__(self) -> AsyncCoho:",
            f"{INDENT}{INDENT}return self",
            "",
            f"{INDENT}async def __aexit__(self, *_: object) -> None:",
            f"{INDENT}{INDENT}await self.aclose()",
        ]
    else:
        lines += [
            f"{INDENT}def close(self) -> None:",
            f"{INDENT}{INDENT}self.content.close()",
            "",
            f"{INDENT}def __enter__(self) -> Coho:",
            f"{INDENT}{INDENT}return self",
            "",
            f"{INDENT}def __exit__(self, *_: object) -> None:",
            f"{INDENT}{INDENT}self.close()",
        ]
    return lines


def _rebuild(models: Sequence[str]) -> list[str]:
    """Completes the models once all exist, since each one's annotations name the others."""
    if not models:
        return []
    listed = f"({models[0]},)" if len(models) == 1 else f"({', '.join(models)})"
    return [
        "# Each model's annotations name the others, so they are completed here, once all exist.",
        "_namespace = dict(globals())",
        f"for _model in {listed}:",
        f"{INDENT}_model.model_rebuild(_types_namespace=_namespace)",
        "",
    ]
